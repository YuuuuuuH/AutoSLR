from contextlib import redirect_stderr, redirect_stdout
from io import StringIO
import argparse
import copy
from pathlib import Path
from tempfile import TemporaryDirectory
from types import SimpleNamespace
from unittest.mock import patch

import pandas as pd

from scripts.common import BASE, ENDPOINT, author_config, digest, dispatch, now, save, verify_vendor, write_jsonl

FIXED = ["--base-url", "https://api.openai.com/v1", "--no-responses-api", "--no-hit-async",
         "--article-doc-status", "metadata", "--reasoning-effort", "high",
         "--max-completion-tokens", "65536", "--abstract-screening-batch-size", "64",
         "--abstract-screening-concurrency", "8"]


def capture_requests(config):
    if config.stage != "abstract_screen":
        raise ValueError("Only title and abstract screening is supported")
    from utils import openai_wrapper
    seen = []

    def create(**kwargs):
        seen.append(copy.deepcopy(kwargs))
        return SimpleNamespace(choices=[SimpleNamespace(message=SimpleNamespace(content="<decision>EXCLUDE</decision>"))])

    def client(*args, **kwargs):
        return SimpleNamespace(chat=SimpleNamespace(completions=SimpleNamespace(create=create)))

    def reject(*args, **kwargs):
        raise RuntimeError("Unexpected network/API path during offline capture")

    with TemporaryDirectory(prefix="agentslr-offline-") as temporary:
        root = Path(temporary)
        offline = copy.copy(config)
        offline.api_key = "offline-fixture"
        offline.save_traces = False
        offline.abstract_screening_path = root / "abstract_screening.csv"
        offline.articles_with_markdown_path = root / "articles_with_markdown.csv"
        if offline.responses_api or offline.hit_async:
            raise ValueError("This baseline capture requires synchronous Chat Completions")
        with patch.object(openai_wrapper, "OpenAI", client), patch.object(openai_wrapper, "AsyncOpenAI", reject), \
                patch("socket.socket.connect", reject), redirect_stdout(StringIO()), redirect_stderr(StringIO()):
            dispatch(offline)
        selected = pd.read_csv(offline.abstract_screening_path)
        if len(selected) != len(seen) or "article_id" not in selected or not selected.article_id.is_unique:
            raise ValueError("Captured requests must map one-to-one to unique article_id rows")
        records = [{"custom_id": f"{config.pathogen}/{article}", "method": "POST", "url": ENDPOINT, "body": body}
                   for article, body in zip(selected.article_id, seen)]
        generated = ["ai4epi_abstract_response", "ai4epi_abstract_decision", "to_ocr", "screening_timestamp"]
        return records, selected.drop(columns=generated, errors="ignore")


def screening_config(args, *, offline=False):
    verify_vendor()
    cli = [*FIXED, "--pathogen", args.pathogen, "--model-name", args.model,
           "--data-dir", str(args.data_dir.resolve()), "--screening-input", str(args.input.resolve()),
           "--client-dir-name", args.model,
           "--config-json", str(BASE / "config.json")]
    if args.sample_size:
        cli.extend(["--sample-size", str(args.sample_size), "--sample-seed", "7"])
    return author_config("abstract_screen", cli, offline=offline)


def add_screen_args(parser):
    parser.add_argument("--pathogen", required=True)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--model", choices=["gpt-6.1-terra", "gpt-5.2-2025-12-11"], default="gpt-6.1-terra")
    parser.add_argument("--data-dir", type=Path, default=BASE / "data/agentslr")
    parser.add_argument("--sample-size", type=int)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Run title and abstract screening, or capture requests offline.")
    add_screen_args(parser)
    parser.add_argument("--dry-run", action="store_true", help="Export requests generated by the original implementation offline")
    parser.add_argument("--output", type=Path, default=BASE / "outputs/preflight")
    args = parser.parse_args(argv)
    config = screening_config(args, offline=args.dry_run)
    if not args.dry_run:
        if not config.api_key or config.api_key == "6767":
            raise SystemExit("Set OPENAI_API_KEY before screening")
        return dispatch(config)
    requests, _ = capture_requests(config)
    args.output.mkdir(parents=True, exist_ok=True)
    write_jsonl(args.output / "requests.jsonl", requests)
    save(args.output / "preflight.json", {"created_utc": now(), "stage": config.stage, "pathogen": config.pathogen,
         "input_sha256": digest(args.input), "model": config.model_name, "requests": len(requests),
         "requests_sha256": digest(args.output / "requests.jsonl"), "model_calls": 0})
    print(f"Captured {len(requests)} requests offline in {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
